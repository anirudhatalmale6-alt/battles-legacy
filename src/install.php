/** Write config.php from an array of settings (merged over the example defaults). */
function write_config(array $settings) {
    $base = require __DIR__ . '/../config.example.php';
    $cfg = array_merge($base, $settings);
    $php = "<?php\n/** Generated by the installer. */\nreturn " . var_export($cfg, true) . ";\n";
    $file = __DIR__ . '/../config.php';
    if (file_put_contents($file, $php) === false) return [false, "Could not write config.php — check folder permissions."];
    return [true, "config.php written."];
}

/** Create every table (driver-aware). Safe to re-run. */
function install_migrate() {
